#!/usr/bin/env python3
"""Write userspace/lib/psvr2_lens_lut.h from Sony's PSVR2 driver DLL.

The three 1024-entry radial lens tables (red, green, blue) at
0x180261180/0x180262180/0x180263180 are measured lens data used by
ComputeDistortion and the hidden-area mesh (docs/sony-re/display.md 5.2,
5.3). Only the raw float values are copied, as IEEE-754 bit patterns.

  extract_lens_lut.py <driver_playstation_vr2_orig.dll> <out.h>
"""
import struct
import sys

from extract_led_models import reader

TABLES = (("red", 0x180261180), ("green", 0x180262180), ("blue", 0x180263180))


def main():
    read = reader(sys.argv[1])
    out = ["/* Generated by scripts/sony-re/extract_lens_lut.py from Sony's PSVR2",
           " * driver: radial lens scale per colour, indexed by r^2 * 1023. */",
           "#ifndef PSVR2_LENS_LUT_H", "#define PSVR2_LENS_LUT_H", "#include <stdint.h>", "",
           "static const uint32_t psvr2_lens_lut_bits[3][1024] = {"]
    for name, va in TABLES:
        vals = struct.unpack("<1024I", read(va, 4096))
        out.append(f"\t{{ /* {name} */")
        for i in range(0, 1024, 8):
            out.append("\t\t" + ", ".join(f"0x{v:08x}" for v in vals[i:i + 8]) + ",")
        out.append("\t},")
    out += ["};", "", "#endif", ""]
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
