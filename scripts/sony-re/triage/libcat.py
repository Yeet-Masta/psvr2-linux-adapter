"""Generate docs/sony-re/catalogue/library.md: library functions identified by
evidence that names them one by one.

Evidence, strongest first:
  flirt  IDA FLIRT match from the MSVC signature sets (out/flirt.txt from
         q_flirt.py), with MFC/ATL/unknown names dropped (the DLL links no
         MFC or ATL, so those are short-body collisions)
  vtable the function sits in a library class's RTTI vtable
  string the function references a string that identifies it
Rows: every function no other doc names yet, FLIRT rows for any verdict,
vtable/string rows for fluff only. Output in our own words; names are
library (not Sony) symbols.
"""
import collections, glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "out")
ADAPTER = r"C:\Users\Yeet Masta\Claude\psvr2-linux-adapter"
DST = os.path.join(ADAPTER, "docs", "sony-re", "catalogue", "library.md")
GEN = ("trivial.md", "library.md")

FAMILY = {
    "lib:linalg": "CLAPACK / BLAS (f2c translation, single precision)",
    "lib:json+config": "jsoncpp",
    "lib:crt": "MSVC C runtime",
    "lib:misc": "MSVC C++ standard library and `RnD` allocator",
    "import/thunk": "MSVC runtime glue (import thunks, unwind funclets)",
    "init": "static initialisers",
    "math+threads": "OpenCV-derived math / `Framework` threads",
}


def first_col(path, t):
    if os.path.basename(path) in GEN:
        return "\n".join(l.split("|")[1] for l in t.splitlines() if l.startswith("| `0x"))
    return t


tri = {}
with open(os.path.join(OUT, "triage.tsv"), encoding="utf-8") as f:
    hdr = f.readline().rstrip("\n").split("\t")
    for l in f:
        r = dict(zip(hdr, l.rstrip("\n").split("\t"))); tri[int(r["va"], 16)] = r
feat = {}
with open(os.path.join(OUT, "features.jsonl"), encoding="utf-8") as f:
    for l in f:
        j = json.loads(l); feat[int(j["va"], 16)] = j
flirt = {}
with open(os.path.join(OUT, "flirt.txt"), encoding="utf-8") as f:
    for l in f:
        if l.startswith("#"):
            continue
        va, before, name, flags, dm = l.rstrip("\n").split("\t")
        flirt[int(va, 16)] = dm
named = set()
rx = re.compile(r"(?:0x|FUN_|sub_)(18[0-9a-fA-F]{7})\b")
for d in glob.glob(os.path.join(ADAPTER, "docs", "**", "*.md"), recursive=True):
    if os.path.abspath(d) == os.path.abspath(DST):
        continue
    with open(d, encoding="utf-8", errors="replace") as f:
        named.update(int(m.group(1), 16) for m in rx.finditer(first_col(d, f.read())))

BAD = re.compile(r"\bC[A-Z][A-Za-z0-9]+::|\bATL::|CMFC|unknown_libname|^sub_|dtor\$|_\d+$"
                 r"|\bC[A-Z][a-z]+[A-Z]\w*\b|^_?kbhit|^Afx|^Concurrency::|_DeleteExceptionPtr")
VT = re.compile(r"const (.+)::`vftable'")


def short(dm):
    dm = re.sub(r"<lambda_[0-9a-f]+>", "<lambda>", dm)
    dm = re.sub(r"std::allocator<[^<>]*(<[^<>]*>)?[^<>]*>", "alloc", dm)
    return dm if len(dm) <= 110 else dm[:107] + "..."


rows = collections.defaultdict(list)
for va, r in sorted(tri.items()):
    if va in named:
        continue
    j = feat.get(va, {})
    v, sub = r["verdict"], r["subsystem"]
    ev = role = None
    if va in flirt and not BAD.search(flirt[va]):
        ev, role = "flirt", f"`{short(flirt[va])}`"
    elif v == "fluff" and j.get("vt"):
        cls = [m.group(1) for x in j["vt"] if (m := VT.search(x))]
        if cls:
            ev, role = "vtable", "virtual method of " + ", ".join(f"`{c}`" for c in sorted(set(cls))[:2])
    elif v == "fluff" and j.get("strs"):
        ss = [s for s in j["strs"] if len(s) >= 4][:2]
        if ss:
            ev = "string"
            role = "uses " + ", ".join("'" + s[:60].replace("|", "/").replace("\n", " ").strip() + "'" for s in ss)
    if not ev:
        continue
    if ev == "flirt":
        fam = "MSVC C++ standard library" if re.match(r"(std::|__std_|Concurrency::)", flirt[va]) else "MSVC C runtime"
    elif ev == "vtable" and "std::" in role:
        fam = "MSVC C++ standard library"
    else:
        fam = FAMILY.get(sub, r["area"])
    rows[sub].append((va, v, ev, role, fam))

n = sum(len(x) for x in rows.values())
cnt = collections.Counter(e for x in rows.values() for _, _, e, _, _ in x)
o = ["# Function catalogue: library and runtime code", "",
     "Generated by `scripts/sony-re/triage/libcat.py`. Each row is a function",
     "that one piece of evidence identifies: an IDA FLIRT match from the MSVC",
     "signature sets (`flirt`; MFC, ATL and unnamed matches are dropped as",
     "collisions: the DLL links none of them), the RTTI vtable of a library",
     "class it sits in (`vtable`), or a string it uses (`string`). Vtable",
     "rows are `[sure]` for the class; FLIRT and string rows are `[likely]`",
     "(FLIRT can collide on short bodies). String rows outside the library",
     "families are Sony fluff (VrTrace dumpers, companion-app dialogs)",
     "named by their log text. None of this code needs porting: the Linux",
     "driver uses the system's C++ library, jsoncpp and LAPACK.", "",
     "`lib:linalg` (`0x180070950`–`0x18009ffe0`) is an f2c translation of",
     "CLAPACK/BLAS in single precision: it passes the Fortran option strings",
     "('No transpose', 'Lower', 'Non-unit', 'Right') and calls the error",
     "handler with routine names such as SGETRF and SGETRI. The tracker",
     "uses it for small matrix factorisations and inverses [likely].", "",
     f"{n} functions: " + ", ".join(f"{k} {c}" for k, c in cnt.most_common()) + ".", ""]
for sub in sorted(rows):
    o += [f"## {sub} ({len(rows[sub])})", "",
          "| Function | Verdict | Evidence | Identity / role | Library |",
          "|----------|---------|----------|-----------------|---------|"]
    for va, v, ev, role, fam in rows[sub]:
        o.append(f"| `0x{va:x}` | {v} | {ev} | {role} | {fam} |")
    o.append("")
with open(DST, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(o))
print(n, dict(cnt), "->", DST)
